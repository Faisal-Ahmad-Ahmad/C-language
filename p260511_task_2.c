#include <stdio.h>

int main(){
	
	printf("================ C ESCAPE SEQUENCES REFERENCE ================  \n\n");
	
	printf("1.  To print a double quote, write:\t\t\\\"  \n");
	printf("2.  To print a literal backslash, write:\t\\\\  \n");
	printf("3.  To insert a newline break, write:\t\t\\n  \n");
	printf("4.  To insert a horizontal tab stop, write:\t\\t  \n");
	printf("5.  To print a percent sign, write:\t\t%%%%  \n\n");
		
	printf("==============================================================  \n\n");

	return 0;
}
